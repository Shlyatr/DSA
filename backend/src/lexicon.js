// --- Проверка служебного токена --------------------------------------------
export function isStopToken(token) {
  if (!token) return true;
  const t = token.toLowerCase().replace(/[.,;:()«»"'’]/g, '');
  if (!t) return true;
  if (STOP_TOKENS.has(t)) return true;
  if (t.startsWith('қалас') || t.startsWith('облыс') || t.startsWith('республик')) return true;
  return false;
}

