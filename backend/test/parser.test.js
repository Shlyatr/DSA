import { test } from 'node:test';
import assert from 'node:assert/strict';
import { parseAddress } from '../src/parser.js';

function check(raw, expected) {
  const got = parseAddress(raw);
  for (const [key, value] of Object.entries(expected)) {
    assert.equal(got[key], value, `${key}: got ${JSON.stringify(got[key])}, want ${JSON.stringify(value)} (raw: ${raw})`);
  }
  return got;
}

