test('мусор и экзотика не роняют парсер и возвращают полный набор полей', () => {
  const garbage = [
    '', '   ', '\u200b\u200b', '12345', 'кв', 'кв 5', 'дом', ',,,,', '/', '//', 'г.', 'ул.', 'мкр',
    'жк', 'область', 'Алматы Алматы Алматы', '1/2/3/4', '%%% ### @@@', 'a'.repeat(5000),
    'кв кв кв 1 2 3', 'подъезд этаж кв дом', 'ул ул ул', 'пр пр пр 1', null, undefined, 42,
  ];
  const fields = ['id', 'raw_address', 'province', 'city', 'district', 'living_area', 'street_type',
    'street_name', 'house', 'apartment', 'entrance', 'floor', 'landmark', 'confidence'];
  for (const raw of garbage) {
    const got = parseAddress(raw);
    for (const f of fields) assert.ok(f in got, `нет поля ${f} для ${JSON.stringify(raw)}`);
    assert.ok(got.confidence >= 0 && got.confidence <= 1);
  }
});

test('номера домов и квартир всегда строки', () => {
  const got = parseAddress('Ул. Курильская 9 кв 1');
  assert.equal(typeof got.house, 'string');
  assert.equal(typeof got.apartment, 'string');
});
